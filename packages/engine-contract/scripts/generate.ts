/**
 * `pnpm codegen` for the engine contract: Zod → JSON Schema → Pydantic v2 models.
 * Writes schema/engine-contract.json and services/engine/src/orrery_engine/generated/contract.py.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { CONTRACT_VERSION, contractSchemas } from "../src/schemas.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const schemaPath = join(root, "packages/engine-contract/schema/engine-contract.json");
const modelPath = join(root, "services/engine/src/orrery_engine/generated/contract.py");

const registry = z.registry<{ id: string; title: string }>();
for (const schema of Object.values(contractSchemas)) {
  const meta = schema.meta() as { id: string; title: string };
  registry.add(schema, meta);
}
const emitted = z.toJSONSchema(registry, {
  target: "draft-2020-12",
  io: "input",
  uri: (id) => `#/$defs/${id}`,
});
const defs = Object.fromEntries(
  Object.entries(emitted.schemas).map(([id, schema]) => {
    const { $schema: _drop, $id: _id, ...rest } = schema as Record<string, unknown>;
    return [id, rest];
  }),
);
const document = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  title: "OrreryEngineContract",
  description: `Orrery worker-engine contract, version ${CONTRACT_VERSION}. Generated from packages/engine-contract; do not edit.`,
  $defs: defs,
};
mkdirSync(dirname(schemaPath), { recursive: true });
writeFileSync(schemaPath, `${JSON.stringify(document, null, 2)}\n`);

mkdirSync(dirname(modelPath), { recursive: true });
execFileSync(
  "uv",
  [
    "run",
    "--frozen",
    "datamodel-codegen",
    "--input", schemaPath,
    "--input-file-type", "jsonschema",
    "--output", modelPath,
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.13",
    "--snake-case-field",
    "--allow-population-by-field-name",
    "--extra-fields", "forbid",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--enum-field-as-literal", "all",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters", "ruff-format",
    "--custom-file-header",
    "# Generated by packages/engine-contract (pnpm codegen) from schema/engine-contract.json. Do not edit.",
  ],
  { cwd: root, stdio: ["ignore", "inherit", "inherit"] },
); // biome-ignore format: flag and value pairs
writeFileSync(join(dirname(modelPath), "__init__.py"), '"""Generated code. Do not edit."""\n');
