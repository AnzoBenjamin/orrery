/**
 * Regenerates src/schema/auth.ts from src/auth-options.ts with the Better Auth CLI, then applies
 * two repository rules the CLI does not know about (tech.md, platform-foundation 3.4):
 *   - primary keys default to Postgres 18's uuidv7() instead of gen_random_uuid() (v4)
 *   - timestamps are timestamptz
 * Run through `pnpm codegen`. The output is committed; `pnpm check` fails if it is stale.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = fileURLToPath(new URL("..", import.meta.url));
const target = join(packageDir, "src/schema/auth.ts");
const scratch = mkdtempSync(join(tmpdir(), "orrery-auth-schema-"));
const raw = join(scratch, "auth.ts");

try {
  execFileSync(
    "pnpm",
    ["exec", "auth", "generate", "--config", "better-auth.config.ts", "--output", raw, "--yes"],
    {
      cwd: packageDir,
      stdio: ["ignore", "ignore", "inherit"],
      env: { ...process.env, BETTER_AUTH_URL: "http://localhost" },
    },
  );
  let source = readFileSync(raw, "utf8");

  const uuidDefaults = source.match(/pg_catalog\.gen_random_uuid\(\)/g)?.length ?? 0;
  if (uuidDefaults === 0) throw new Error("generator output changed: no uuid defaults found");
  source = source.replaceAll("pg_catalog.gen_random_uuid()", "uuidv7()");

  source = source.replace(/timestamp\("([a-z_]+)"\)/g, 'timestamp("$1", { withTimezone: true })');
  if (/timestamp\("[a-z_]+"\)/.test(source)) throw new Error("timestamp rewrite incomplete");

  writeFileSync(
    target,
    `// Generated by scripts/generate-auth-schema.ts from src/auth-options.ts. Do not edit.\n${source}`,
  );
  execFileSync("pnpm", ["exec", "biome", "check", "--write", target], {
    cwd: packageDir,
    stdio: "ignore",
  });
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
