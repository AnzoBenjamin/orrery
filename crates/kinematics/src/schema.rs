//! The mechanism graph, as generated from `packages/schema/schema/mechanism.json` by
//! `cargo typify` (`pnpm codegen`). The Zod schema is the source of truth; this module only
//! adds parsing helpers.

#[allow(
    clippy::all,
    clippy::pedantic,
    missing_debug_implementations,
    reason = "generated by cargo typify"
)]
#[path = "generated/mechanism.rs"]
mod generated;

pub use generated::*;

/// Why a mechanism document could not be read.
#[derive(Debug, thiserror::Error)]
pub enum ParseError {
    #[error("the mechanism document is not valid JSON or does not match the schema: {0}")]
    Json(#[from] serde_json::Error),
    #[error("schema version {found} is not supported; this build reads version {expected}")]
    UnsupportedVersion { found: f64, expected: f64 },
}

/// The schema version this build reads.
pub const SCHEMA_VERSION: f64 = 1.0;

/// Parses a mechanism document. Structure is checked here; the cross-reference rules (dangling
/// ids, a single ground body) are checked when a solver is built from the graph.
pub fn parse_mechanism(json: &str) -> Result<Mechanism, ParseError> {
    let mechanism: Mechanism = serde_json::from_str(json)?;
    if mechanism.schema_version.to_bits() != SCHEMA_VERSION.to_bits() {
        return Err(ParseError::UnsupportedVersion {
            found: mechanism.schema_version,
            expected: SCHEMA_VERSION,
        });
    }
    Ok(mechanism)
}

/// Serializes a mechanism to a JSON document.
pub fn to_json(mechanism: &Mechanism) -> Result<String, serde_json::Error> {
    serde_json::to_string(mechanism)
}
