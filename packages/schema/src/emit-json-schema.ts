/**
 * `pnpm codegen` for the mechanism graph: Zod → JSON Schema (schema/mechanism.json).
 * Rust types (cargo typify, crates/kinematics) and Python models (datamodel-code-generator) are
 * generated from that file.
 *
 * Draft-07 is emitted because typify reads tuples only in draft-07 form. Union variants stay
 * inline (no `id`), so generators see each variant's `kind` or `type` constant and produce tagged
 * enums. The cross-reference rules in `mechanismSchema`'s refinement (dangling ids, ground body,
 * driver targets) cannot be expressed in JSON Schema; every consumer also validates through the
 * Zod schema or the solver.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { mechanismSchemaBase } from "./mechanism.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const outputPath = join(root, "packages/schema/schema/mechanism.json");
const rustPath = join(root, "crates/kinematics/src/generated/mechanism.rs");
const pythonPath = join(root, "services/engine/src/orrery_engine/generated/mechanism.py");

const emitted = z.toJSONSchema(mechanismSchemaBase, { target: "draft-7", io: "input" }) as {
  definitions?: Record<string, Record<string, unknown>>;
};
// The root is the Mechanism definition itself, so generators name the root type Mechanism.
const { Mechanism: rootDefinition, ...definitions } = emitted.definitions ?? {};
if (!rootDefinition) throw new Error("the Mechanism schema has no definition id");
const { id: _id, ...rootBody } = rootDefinition;

const document = {
  $schema: "http://json-schema.org/draft-07/schema#",
  title: "Mechanism",
  description: "Orrery mechanism graph. Generated from packages/schema; do not edit.",
  ...rootBody,
  definitions,
};

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(document, null, 2)}\n`);

// Rust types for crates/kinematics. BTreeMap keeps serialized maps in a stable order.
mkdirSync(dirname(rustPath), { recursive: true });
execFileSync(
  "cargo",
  [
    "typify",
    outputPath,
    "--no-builder",
    "--map-type",
    "::std::collections::BTreeMap",
    "--output",
    rustPath,
  ],
  { cwd: root, stdio: ["ignore", "inherit", "inherit"] },
);
// Formatted with the workspace's rustfmt settings so `cargo fmt --check` passes unchanged.
execFileSync("rustfmt", ["--edition", "2024", rustPath], {
  cwd: root,
  stdio: ["ignore", "inherit", "inherit"],
});

// Pydantic v2 models for the engine, with the flags the engine contract uses.
execFileSync(
  "uv",
  [
    "run",
    "--frozen",
    "datamodel-codegen",
    "--input", outputPath,
    "--input-file-type", "jsonschema",
    "--output", pythonPath,
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.13",
    "--snake-case-field",
    "--allow-population-by-field-name",
    "--use-title-as-name",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--enum-field-as-literal", "all",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters", "ruff-format",
    "--custom-file-header",
    "# Generated by packages/schema (pnpm codegen) from schema/mechanism.json. Do not edit.",
  ],
  { cwd: root, stdio: ["ignore", "inherit", "inherit"] },
); // biome-ignore format: flag and value pairs
